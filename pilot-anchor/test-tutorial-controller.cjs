"use strict";
// A replacement view with no DOM, disabled buttons, or timers of its own.
// Progression, completion, and saved training state must remain controller-owned.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = __dirname;
const plain = value => JSON.parse(JSON.stringify(value));

function harness() {
  let now = 0, nextTimer = 1, engine, events, model;
  const timers = new Map(), backups = [], exposures = [], stages = [];
  const device = { tutorialLog: [] }, dragTutState = { active: false, done: false };
  const clock = {
    readWait: 100,
    advance(ms) {
      now += ms;
      for (;;) {
        const ready = [...timers].filter(([, timer]) => timer.at <= now).sort((a, b) => a[1].at - b[1].at || a[0] - b[0]);
        if (!ready.length) break;
        const [id, timer] = ready[0]; timers.delete(id); timer.fn();
      }
    },
    finishReading() { this.advance(this.readWait * 2); },
  };
  const context = {
    performance: { now: () => now }, URLSearchParams,
    setTimeout(fn, delay = 0) { const id = nextTimer++; timers.set(id, { fn, at: now + delay }); return id; },
    clearTimeout(id) { timers.delete(id); },
  };
  context.window = context;
  vm.createContext(context);
  vm.runInContext(fs.readFileSync(path.join(root, "guided-tutorial.js"), "utf8"), context);
  const config = context.PILOT_GUIDED_TUTORIAL;
  config.createView = (_env, getters, callbacks) => {
    model = getters; events = callbacks;
    const noop = () => {};
    return {
      build: noop, prepareRender: noop, showStep: noop, showStage: noop, playGraphics: noop,
      place: noop, renderQuiz: noop, focusQuizAnswer: noop, prepareTeardown: noop, hide: noop,
      enter: noop, resetFlash: noop, flash: noop, clearHint: noop, animate: noop,
      removeCue: noop, addCue: noop, setWaiting: noop, clearWaiting: noop,
      isHeld: () => false, motionSnapshot: () => null,
    };
  };
  vm.runInContext(fs.readFileSync(path.join(root, "js/tutorial-controller.js"), "utf8"), context);
  engine = config.createEngine({
    dragTutState, instructedSteps: [], realBlocks: [], query: new URLSearchParams(), debug: false,
    getDevice: () => device, setResumeStage: stage => stages.push(stage),
    saveBackup: () => backups.push(plain(engine.snapshot())),
    logInstructionExposure: (kind, value) => exposures.push({ kind, ...plain(value) }),
    minReadMs: () => clock.readWait, readCueDelay: () => clock.readWait,
    hideBanner() {}, clearIdleCoach() {}, coachHide() {}, setCoach() {}, show() {},
    sizeCanvas() {}, clearCanvas() {}, updateProgress() {},
  });
  return { engine, events, model, config, clock, backups, exposures, stages, device, dragTutState };
}

// Establish motor completion through the public view event, then represent a
// legitimate reload at the quiz. Answer orders are generated by the controller.
function atQuiz(h, onDone = () => {}) {
  h.engine.run(() => {}, { start: "motor" });
  h.events.motorComplete();
  const restored = plain(h.engine.snapshot());
  restored.stepId = "rule-check";
  restored.index = h.config.steps.findIndex(step => step.id === "rule-check");
  h.engine.run(onDone, { restored });
}

function completeQuiz(h) {
  for (const q of h.config.checks) {
    h.events.answer(q.correctIndex, false, q);
    h.clock.finishReading(); h.events.advance();
  }
}

let passed = 0;
function test(name, fn) { fn(); passed++; console.log("PASS tutorial controller: " + name); }

test("a direct advance from a replacement view cannot bypass the injected reading lock", () => {
  const h = harness(); h.engine.run(() => {});
  const first = h.engine.snapshot().stepId;
  assert(h.engine.state().lockRemainingMs > 0);
  h.events.advance(); h.events.advance();
  assert.equal(h.engine.snapshot().stepId, first);
  h.clock.finishReading(); h.events.advance();
  assert.notEqual(h.engine.snapshot().stepId, first);
});

test("motor completion is required even when the replacement view has no disabled button", () => {
  const h = harness(); h.engine.run(() => {}, { start: "motor" });
  h.clock.finishReading(); h.events.advance();
  assert.equal(h.engine.snapshot().stepId, "motor");
  assert.equal(h.engine.state().handsDone, false);
  h.events.motorComplete(); h.events.advance();
  assert.equal(h.engine.state().handsDone, true);
  assert.notEqual(h.engine.snapshot().stepId, "motor");
});

test("wrong answers cannot advance and all seven correct answers complete training", () => {
  const h = harness(); let completions = 0; atQuiz(h, () => completions++);
  const first = h.config.checks[0];
  h.events.answer((first.correctIndex + 1) % first.labels.length, false, first);
  h.clock.finishReading(); h.events.advance();
  assert.equal(h.engine.state().quiz.index, 0); assert.equal(completions, 0);
  assert.equal(h.engine.state().completedTraining, false);
  for (let index = 0; index < h.config.checks.length; index++) {
    const q = h.config.checks[index]; h.events.answer(q.correctIndex, false, q);
    if (index === 0) {
      // The reading lock has already expired, so this answer may advance now.
      h.events.advance();
    } else {
      h.events.advance(); assert.equal(h.engine.state().quiz.index, index);
      h.clock.finishReading(); h.events.advance();
    }
    if (index < h.config.checks.length - 1) assert.equal(completions, 0);
  }
  assert.equal(h.config.checks.length, 7);
  assert.equal(completions, 1); assert.equal(h.dragTutState.done, true);
  assert.equal(h.engine.state().completedTraining, true);
  assert.equal(h.engine.state().quiz.complete, true);
  assert.equal(h.device.guidedTutorial.completed, true);
  assert.equal(h.backups.at(-1).completedTraining, true);
});

test("snapshot restores quiz position, shuffled answer order, selections, and attempts in a new view", () => {
  const h = harness(); atQuiz(h);
  h.events.answer(h.config.checks[0].correctIndex, false, h.config.checks[0]);
  h.clock.finishReading(); h.events.advance();
  const second = h.config.checks[1]; h.events.answer((second.correctIndex + 1) % second.labels.length, false, second);
  const saved = plain(h.engine.snapshot());
  const resumed = harness(); resumed.engine.run(() => {}, { restored: saved });
  const actual = plain(resumed.engine.snapshot());
  assert.equal(actual.stepId, saved.stepId); assert.equal(actual.index, saved.index);
  assert.deepEqual(actual.quiz, saved.quiz); assert.deepEqual(actual.completed, saved.completed);
  assert.equal(resumed.model.quizSelection(), saved.quiz.selections[saved.quiz.index]);
  assert.equal(resumed.engine.state().completedTraining, false);
  resumed.clock.finishReading(); resumed.events.advance();
  assert.equal(resumed.engine.state().quiz.index, saved.quiz.index);
});

test("resuming an instruction preserves its step and previously achieved motor completion", () => {
  const h = harness(); h.engine.run(() => {}, { start: "motor" }); h.events.motorComplete(); h.events.advance();
  h.clock.finishReading(); h.events.advance();
  const saved = plain(h.engine.snapshot());
  assert.notEqual(saved.stepId, "motor");
  const resumed = harness(); resumed.engine.run(() => {}, { restored: saved });
  assert.equal(resumed.engine.snapshot().stepId, saved.stepId);
  assert.equal(resumed.engine.state().handsDone, true);
});

test("closing optional replay restores the completed snapshot without writing training saves", () => {
  const h = harness(); atQuiz(h); completeQuiz(h);
  assert.equal(h.engine.state().completedTraining, true);
  const initial = plain(h.engine.snapshot()), backupsBefore = h.backups.length, stagesBefore = h.stages.length;
  let returned = 0; h.engine.run(() => returned++, { replay: true, start: "rule-check" });
  const q = h.config.checks[0];
  h.events.answer((q.correctIndex + 1) % q.labels.length, false, q);
  h.clock.finishReading(); h.events.advance();
  assert.equal(h.engine.state().review, true);
  assert.equal(h.model.canClose(), true);
  h.events.close();
  assert.equal(returned, 1); assert.equal(h.engine.state().review, false);
  assert.deepEqual(plain(h.engine.snapshot()), initial);
  assert.equal(h.backups.length, backupsBefore); assert.equal(h.stages.length, stagesBefore);
  assert.equal(h.device.guidedTutorial.completed, true);
});

test("measuring every quiz label is read-only and retains the initial last-question label", () => {
  const h = harness(); atQuiz(h);
  const before = plain({ snapshot: h.engine.snapshot(), device: h.device, backups: h.backups, stages: h.stages });
  const labels = h.config.checks.map((_, index) => h.model.nextLabel(index));
  assert.deepEqual(plain(labels), [...Array(6).fill("次へ"), "例題へ"]);
  assert.equal(h.model.nextLabel(), "次へ");
  assert.deepEqual(plain({ snapshot: h.engine.snapshot(), device: h.device, backups: h.backups, stages: h.stages }), before);
});

test("measuring replay labels follows its return label without changing the current question or saves", () => {
  const h = harness(), returnLabel = "課題の続きに戻る";
  h.engine.run(() => {}, { replay: true, start: "rule-check", returnLabel });
  const before = plain({ snapshot: h.engine.snapshot(), device: h.device, backups: h.backups, stages: h.stages });
  const labels = h.config.checks.map((_, index) => h.model.nextLabel(index));
  assert.deepEqual(plain(labels), [...Array(6).fill("次へ"), returnLabel]);
  assert.equal(h.model.nextLabel(), "次へ");
  assert.deepEqual(plain({ snapshot: h.engine.snapshot(), device: h.device, backups: h.backups, stages: h.stages }), before);
  for (let i = 0; i < 6; i++) h.events.advance();
  assert.equal(h.model.nextLabel(), returnLabel);
});

